"""翻訳モデルの変換（ADR-16）。

入手した翻訳モデルを、実行基盤（CTranslate2）の形式へ 1 回だけ変換する。

変換は、モデル管理部が起動する、変換の間だけ動く別のプロセスで行う。
アプリサーバーとも 2 つのワーカーとも別のプロセスで、終わると（成功しても失敗しても）止まる。
止まると、変換で使ったメモリが確実に戻る。アプリサーバーのメモリの上限（0.5GB）に、
変換前の翻訳モデルと変換の部品は収まらないため、アプリサーバーの中では変換しない。

構成（どちらのプロセスで動くかで分けている）

    アプリサーバー側（標準ライブラリだけ。変換の部品を取り込まない）
    - layout.py     変換後のフォルダー・作業用のフォルダー・控えの置き場所
    - protocol.py   子が親へ返す結果の形（信頼しない出力として、厳密に検証して読む）
    - process.py    変換プロセスを起動して終わりまで見届ける
    - receipt.py    変換後のハッシュ値の控え（作る・照合する）
    - service.py    モデル管理部へ接続する口（TranslationConversion の実装）

    変換プロセス側（`python -m meeting_interpreter.models.conversion` で動く）
    - worker.py         変換の本体。変換の部品を取り込む
    - network_guard.py  外へ通信しない。外への接続と名前の解決を拒み、試みを数える
    - safe_torch.py     pickle 形式の重みを、安全な読み込みだけで読む
    - sandbox.py        OS の仕組みで、ネットワークのソケットを作れなくする

変換に使う部品（PyTorch など）は、イメージの別の環境（/opt/conversion-venv）に入れる。
環境変数 MMD_CONVERSION_PYTHON が、その環境の Python を指す。
方式と部品の版は、docs/models.md にある。
"""
