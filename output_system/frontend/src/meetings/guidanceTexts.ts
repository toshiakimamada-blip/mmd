import type { AudioSource } from '../audio/audioSource';

/** 音声の出どころごとの、取り込み手順の案内。 */
export interface SourceGuidance {
  /** 案内の見出し。 */
  readonly heading: string;
  /** 手順。上から順に行う。 */
  readonly steps: readonly string[];
}

/**
 * 音声の出どころごとの、取り込み手順（F-01・F-02）。
 * 「会議を開始する」を押すと、ブラウザーが共有または許可の確認を出す。確認の画面はブラウザーのもので、
 * アプリは中身を変えられないため、確認で行う操作を手順にする。
 */
export const SOURCE_GUIDANCE: Readonly<Record<AudioSource, SourceGuidance>> = {
  system_audio: {
    heading: '「PC で再生される音声」を取り込む手順',
    steps: [
      '「会議を開始する」を押すと、ブラウザーが画面の共有の確認を出します。',
      '共有する対象は、「画面全体」を選びます。ウィンドウやタブを選ぶと、会議の音声を取り込めないことがあります。',
      '「音声を共有する」（ブラウザーによって、表示は少し異なります）をオンにします。オフのままでは、音声を取り込めません。',
      '「共有」を押します。',
    ],
  },
  microphone: {
    heading: '「マイク」を取り込む手順',
    steps: [
      'マイクを PC につなぎます。',
      '「会議を開始する」を押すと、ブラウザーがマイクの利用の許可を尋ねます。',
      '「許可」を押します。',
      '許可を断ったときは、アドレス欄の左にあるアイコンからマイクを許可し直して、もう一度「会議を開始する」を押します。',
    ],
  },
};

