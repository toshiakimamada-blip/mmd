/**
 * 会議の内容（タイトル・字幕・要約・質問）に含まれる記号を、Markdown と HTML の記法として働かない形へ変換する
 * 純粋な関数（F-13、ADR-15、非機能要件設計書「表示と出力の無害化」）。
 *
 * 取り出す Markdown のファイルでは、会議の内容は、すべてこの変換を通して書く。会議の相手が話した内容（字幕）と
 * AI の出力（要約・質問）が、見出し・リンク・画像・HTML・一覧・表などとして働かないようにするため。
 * 変換した文字列を、Markdown の変換器へ渡したとき、元の文字列が、そのままの文字として表示される。
 * 確かめ方は、test/records/recordMarkdownRendered.test.ts（markdown-it で描画する）と、
 * output_system/docs/record-screen.md「変換の確かめ方」にある。
 *
 * 変換の規則
 *
 * | 対象 | 変換 | 止めるもの |
 * |---|---|---|
 * | `\` `` ` `` `*` `_` `{` `}` `[` `]` `\|` `#` `~` `$` | 前に `\` を付ける | 強調・コード・リンク・画像・表・取り消し線・属性・見出し・タグ・数式 |
 * | 2 つ続く `%%` と `==` | 続く記号のすべての前に `\` を付ける | コメント（`%%`）・強調（`==`）。1 つだけの `%` と `=` は、そのまま |
 * | `<` `>` `&` | `&lt;` `&gt;` `&amp;` | HTML の要素と文字参照。`\<` の形は、`\` を使えない変換器があるため使わない |
 * | 行頭の `-` `+` `=` `:` `!` | 前に `\` を付ける | 箇条書き・区切り線・見出しの下線・定義リスト・注記（`!!!`） |
 * | 行頭の「数字 ＋ `.` または `)`」（あとに空白か行末） | `.` または `)` の前に `\` を付ける | 番号つきの一覧（桁数の上限なし） |
 * | `//` | 1 つ目の `/` の直後に長さ 0 の空白（U+200B）を入れる | `scheme://`・`//host`・全角のコロンのあとの `//` など、`//` で始まる URL の自動リンク |
 * | `@` | 前後の両方に U+200B を入れる | メールアドレスの自動リンク（`@` の直後だけでは、ホスト名の一部として読まれる） |
 * | `www` のあとの `.` | 前に `\` を付ける | `www.` で始まる URL の自動リンク |
 * | 空白・`.`・`\` 以外の文字のあとで、あとに文字が 2 つ以上続く `.` | 前に `\` を付ける | 裸のドメイン（`example.com`）の自動リンク（linkify の fuzzyLink）。ホスト名の文字を広く取るため、`x+.com` なども対象。`3.5`・文末の `.`・`e.g.` には付かない |
 * | `1.2.3.4` の形の IP アドレスの中の `.` | 前に `\` を付ける | IP アドレスの自動リンク（linkify の fuzzyIP） |
 * | 文字の向きを変える文字・見えないタグの文字 | 取り除く | 表示の順序の偽装。ZWJ（U+200D）と ZWNJ（U+200C）は残す（絵文字の結合と一部の言語の文字の区切りに要る）。ファイル名では、書式の文字をすべて `_` にする（exportFileName.ts） |
 * | 行頭と行末の空白 | 取り除く | 字下げのコード・行末の 2 つの空白（改行） |
 * | 改行の別の形（U+2028 など）・制御文字 | 改行・空白にそろえる | 行頭の記法を、別の行として働かせない。ターミナルで表示したときの制御を防ぐ |
 *
 * - `(` `)` と文の途中の `!` は、そのまま残す。単独では何も起こさない（リンク・画像は `[` が要る。`[` は変換する）
 * - URL の自動リンクの止め方: `//` と `@` の割り方は、`\` ではなく U+200B にする。`\` で逃がした文字を、本文へ戻してから
 *   URL を探す変換器があり得るため。ドットは、`\` で逃がす。U+200B は、ドメインの文字として読まれる
 *   （`www\u200B.example.com` が fuzzyLink でリンクになる）ため使えない。U+200B を入れると、表示される文字は元と同じだが、
 *   URL をコピーすると、見えない文字が入る
 * - 網羅できないもの（限界）: `:smile:` の絵文字、GitHub の `#123` や `@名前` の参照のように、変換器と画面の設定で
 *   働く記法は、止めない（`#` と `@` は止めるが、絵文字の `:...:` は止めない）。要素ではなく、決まった画像の文字に変わる
 * - 変換は 1 回だけ行う。変換した結果を、もう一度変換しない（`\` も変換するため、二重になる）
 */

/** 長さ 0 の空白（U+200B）。`//` の間と `@` の前後に差し込む。 */
export const ZERO_WIDTH_SPACE = '\u200B';

/** 改行として扱う文字（CRLF・CR・VT・FF・NEL・行区切り・段落区切り）。LF にそろえる。 */
const LINE_BREAKS = /\r\n|[\r\v\f\u0085\u2028\u2029]/g;

/** 改行とタブを除く制御文字（C0・DEL・C1）。空白にする。 */
const CONTROL_CHARACTERS = /(?![\t\n])\p{Cc}/gu;

/** 文字の向きを変える文字（U+061C・U+200E・U+200F・U+202A〜U+202E・U+2066〜U+2069）と、見えないタグの文字（U+E0000〜U+E007F）。 */
const DIRECTION_AND_TAG_CHARACTERS = /[\u061C\u200E\u200F\u202A-\u202E\u2066-\u2069\u{E0000}-\u{E007F}]/gu;

/** どこにあっても、前に `\` を付けて逃がす文字。`<` `>` `&` は文字参照にする。 */
const SPECIAL_CHARACTERS = /[\\`*_{}[\]|#~$&<>]/g;

/** 文字参照にする文字。 */
const ENTITIES: Readonly<Record<string, string>> = { '&': '&amp;', '<': '&lt;', '>': '&gt;' };

/** 1 文字を、変換した形にする。 */
function escapeCharacter(character: string): string {
  return ENTITIES[character] ?? `\\${character}`;
}

/**
 * 文字列を、改行で行に分け、各行の前後の空白を除く。向きを変える文字とタグの文字は取り除く。
 * 改行の別の形は LF にそろえ、制御文字は空白にする。
 *
 * @param text 会議の内容
 * @returns 行。空の行を含む
 */
function toTrimmedLines(text: string): string[] {
  return text
    .replace(DIRECTION_AND_TAG_CHARACTERS, '')
    .replace(LINE_BREAKS, '\n')
    .replace(CONTROL_CHARACTERS, ' ')
    .split('\n')
    .map((line) => line.trim());
}

/**
 * 1 行の文字列を変換する。行頭の記法も止める。
 *
 * @param line 前後の空白を除いた、改行を含まない 1 行
 * @returns 変換した 1 行
 */
function escapeLine(line: string): string {
  return (
    line
      .replace(SPECIAL_CHARACTERS, escapeCharacter)
      // 2 つ続くと働く拡張記法（コメント %%、強調 ==）。続く記号のすべてを逃がす（1 つだけなら、そのまま）
      .replace(/%(?=%)|(?<=%)%/g, '\\%')
      .replace(/=(?==)|(?<==)=/g, '\\=')
      // 自動リンク: `//`（スキームつきの URL・//host・全角のコロンのあとの //）と、メールアドレスの `@`
      .replace(/\/(?=\/)/g, `/${ZERO_WIDTH_SPACE}`)
      .replace(/@/g, `${ZERO_WIDTH_SPACE}@${ZERO_WIDTH_SPACE}`)
      // 自動リンク: IP アドレスの中のドット（1.2.3.4 の形）
      .replace(/(?<!\d)\d{1,3}(?:\.\d{1,3}){3}(?!\d)/g, (address) => address.replaceAll('.', '\\.'))
      // 自動リンク: www のあとのドットと、裸のドメインのドット（空白・ドット・\ 以外の文字のあとで、あとに文字が 2 つ以上続く。
      // linkify の fuzzyLink は、ホスト名の文字を広く取る（`x+.com`・`~.com`・U+200D のあとの `.com` もリンクになる）。
      // 逃がし済みのドット（IP アドレスの中）には、重ねて付けない）
      .replace(/(?<=www)\.|(?<=[^\s.\\])\.(?=\p{L}{2,})/giu, '\\.')
      // 行頭だけで働く記法: 箇条書き・区切り線・見出しの下線・定義リスト・注記
      .replace(/^[-+=:!]/, (character) => `\\${character}`)
      // 行頭の番号つきの一覧（番号のあとの . または ) を逃がす。あとに空白か行末が続くものだけが一覧になる）
      .replace(/^(\d+)([.)])(?=[ \t]|$)/, '$1\\$2')
  );
}

/**
 * 1 行の内容（タイトル・見出し・箇条書きの項目・字幕の 1 行・質問）を、Markdown の記法として働かない形へ変換する。
 *
 * 改行を含む内容は、1 行に畳む（行ごとの前後の空白を除き、空行を除いて、空白 1 つでつなぐ）。
 * 行の途中で、見出しや一覧が始まらないようにするため。
 * 戻り値は、行頭の記法も止めてあるため、「- 」や「1. 」のあとに続けて置いても、入れ子の記法にならない。
 *
 * @param text 会議の内容
 * @returns 変換した 1 行。内容が空・空白だけのときは空の文字列
 */
export function escapeMarkdownLine(text: string): string {
  return escapeLine(
    toTrimmedLines(text)
      .filter((line) => line !== '')
      .join(' '),
  );
}

/**
 * 複数行の内容（要約の全体の概要）を、Markdown の記法として働かない形へ変換する。
 *
 * 行の構造は保つ。段落の区切りの空行は 1 行にまとめ、前後の空行は除く。どの行も、行頭を含めて変換する。
 * 行末の 2 つの空白（段落の中の改行）は付けない。呼び出し側が、必要な行に付ける。
 *
 * @param text 会議の内容
 * @returns 変換した段落。内容が空・空白だけのときは空の文字列
 */
export function escapeMarkdownParagraph(text: string): string {
  const lines: string[] = [];
  for (const line of toTrimmedLines(text)) {
    if (line === '' && (lines.length === 0 || lines[lines.length - 1] === '')) {
      continue;
    }
    lines.push(line === '' ? '' : escapeLine(line));
  }
  while (lines.length > 0 && lines[lines.length - 1] === '') {
    lines.pop();
  }
  return lines.join('\n');
}
