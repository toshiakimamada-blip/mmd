/**
 * 要約の箇条書き（話題ごとの要点・決定事項・宿題）を、項目に分ける。
 *
 * 箇条書きは、1 行に 1 項目を書いた文字列として保存している（データモデル設計書の「要約」）。
 * 画面は、保存した文字列を 1 行ずつ分けて、箇条書きにする。
 * 項目の文字列は変えない（前後の空白を除くだけ）。表示では文字として扱う（ADR-15）。
 */

/**
 * 保存した文字列を、1 行 1 項目に分ける。
 *
 * @param text 保存した箇条書きの文字列（改行は LF でも CRLF でもよい）
 * @returns 項目。前後の空白を除き、空の行は含めない。項目が無ければ空の配列
 */
export function splitSummaryLines(text: string): string[] {
  return text
    .split(/\r?\n/)
    .map((line) => line.trim())
    .filter((line) => line !== '');
}
